/**
 * generate-search-index.cjs
 *
 * Build-time script that generates a metadata-only Fuse.js search index.
 *
 * CRITICAL GUARDRAIL:
 *   The index NEVER contains full body text of content pages.
 *   Only the following fields are ingested:
 *     - name         (e.g., "sys.dm_exec_requests")
 *     - title        (e.g., "sys.dm_exec_requests")
 *     - slug         (URL-safe identifier)
 *     - category     (e.g., "execution", "wait-statistics")
 *     - tags         (array of keywords)
 *     - description  (MAX 150 characters — excerpt only)
 *
 * Usage:
 *   node scripts/generate-search-index.cjs
 *
 * This script reads from src/data/search-index.json (generated by the
 * Python extraction pipeline) and writes to src/data/searchIndex.ts
 * as a typed TypeScript module consumed by the Astro frontend.
 */

const fs = require("fs");
const path = require("path");

const SEARCH_INDEX_SOURCE = path.join(__dirname, "..", "src", "data", "search-index.json");
const SEARCH_INDEX_OUTPUT = path.join(__dirname, "..", "src", "data", "searchIndex.ts");

// Metadata-only fields — THIS IS THE ALLOWLIST
const ALLOWED_FIELDS = ["name", "title", "slug", "category", "tags", "description"];
const MAX_DESC_LENGTH = 150;

function sanitizeEntry(entry) {
  const sanitized = {};
  for (const field of ALLOWED_FIELDS) {
    if (field in entry) {
      if (field === "description" && typeof entry[field] === "string") {
        sanitized[field] = entry[field].slice(0, MAX_DESC_LENGTH);
      } else if (field === "tags" && Array.isArray(entry[field])) {
        sanitized[field] = entry[field].slice(0, 10); // max 10 tags
      } else {
        sanitized[field] = entry[field];
      }
    }
  }
  return sanitized;
}

function generate() {
  console.log("[generate-search-index] Building search index...");

  // Check if source exists
  if (!fs.existsSync(SEARCH_INDEX_SOURCE)) {
    console.warn(
      "[generate-search-index] WARNING: search-index.json not found at",
      SEARCH_INDEX_SOURCE
    );
    console.warn("[generate-search-index] Creating empty index. Run extraction pipeline first.");
    const emptyIndex = `// Auto-generated search index (metadata-only)\n// Source: extractor/output → schema_mapper.py\n\nexport const searchIndex: SearchEntry[] = [];\n\nexport interface SearchEntry {\n  name: string;\n  title: string;\n  slug: string;\n  category: string;\n  tags: string[];\n  description: string;\n}\n`;
    fs.writeFileSync(SEARCH_INDEX_OUTPUT, emptyIndex, "utf-8");
    return;
  }

  const rawData = JSON.parse(fs.readFileSync(SEARCH_INDEX_SOURCE, "utf-8"));
  const sanitizedIndex = rawData.map(sanitizeEntry);

  // TypeScript output
  const totalEntries = sanitizedIndex.length;
  const categories = [...new Set(sanitizedIndex.map((e) => e.category))];

  let tsContent = `// Auto-generated search index — DO NOT EDIT MANUALLY\n`;
  tsContent += `// Generated: ${new Date().toISOString().split("T")[0]}\n`;
  tsContent += `// Entries: ${totalEntries}\n`;
  tsContent += `// Categories: ${categories.join(", ")}\n`;
  tsContent += `//\n`;
  tsContent += `// GUARDRAIL: Metadata-only. NO full body text is included.\n`;
  tsContent += `// Fields: name, title, slug, category, tags, description (max 150 chars)\n\n`;

  tsContent += `export interface SearchEntry {\n`;
  tsContent += `  name: string;\n`;
  tsContent += `  title: string;\n`;
  tsContent += `  slug: string;\n`;
  tsContent += `  category: string;\n`;
  tsContent += `  tags: string[];\n`;
  tsContent += `  description: string;\n`;
  tsContent += `}\n\n`;

  tsContent += `export const searchIndex: SearchEntry[] = `;
  tsContent += JSON.stringify(sanitizedIndex, null, 2);
  tsContent += `;\n`;

  fs.writeFileSync(SEARCH_INDEX_OUTPUT, tsContent, "utf-8");

  console.log(`[generate-search-index] Done. ${totalEntries} entries written to searchIndex.ts`);
  console.log(`[generate-search-index] Categories: ${categories.join(", ")}`);
  console.log(`[generate-search-index] Sanitized — NO full body text in index. ✓`);
}

generate();
